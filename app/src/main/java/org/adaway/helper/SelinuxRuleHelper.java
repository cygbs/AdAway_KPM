package org.adaway.helper;

import static java.nio.charset.StandardCharsets.UTF_8;

import android.util.Base64;

import com.topjohnwu.superuser.Shell;

import org.adaway.model.root.ShellUtils;

import timber.log.Timber;

/**
 * This class is an helper to install and apply the SELinux rules required by the KPM hosts
 * redirection: the Android resolver ({@code netd}) must be allowed to read the redirected hosts
 * file located in {@code /data/adb}. The rules are persisted as an executable script in
 * {@code /data/adb/post-fs-data.d} so they are re-applied on every boot while SELinux stays
 * enforcing (no permissive mode required).
 *
 * @author AdAway
 */
public final class SelinuxRuleHelper {
    /**
     * The APatch/Magisk boot script directory.
     */
    public static final String POST_FS_DATA_DIR = "/data/adb/post-fs-data.d";
    /**
     * The script file name.
     */
    public static final String SCRIPT_NAME = "adaway_hosts_selinux.sh";
    /**
     * The script file path.
     */
    public static final String SCRIPT_PATH = POST_FS_DATA_DIR + "/" + SCRIPT_NAME;
    /**
     * The script content written to {@link #SCRIPT_PATH}.
     */
    private static final String SCRIPT_CONTENT =
            "#!/system/bin/sh\n" +
                    "# Generated by AdAway - do not edit.\n" +
                    "# Allows the Android resolver (netd) to read the redirected hosts file in /data/adb.\n" +
                    "MAGISKPOLICY=''\n" +
                    "for p in /data/adb/ap/bin/magiskpolicy /data/adb/magisk/magiskpolicy magiskpolicy; do\n" +
                    "  if command -v \"$p\" >/dev/null 2>&1; then MAGISKPOLICY=\"$p\"; break; fi\n" +
                    "done\n" +
                    "[ -z \"$MAGISKPOLICY\" ] && exit 0\n" +
                    "\"$MAGISKPOLICY\" --live 'allow netd adb_data_file dir search' || true\n" +
                    "\"$MAGISKPOLICY\" --live 'allow netd adb_data_file file { read getattr map open }' || true\n";

    /**
     * Private constructor.
     */
    private SelinuxRuleHelper() {
    }

    /**
     * Get the SELinux rules script path.
     *
     * @return The SELinux rules script path.
     */
    public static String getScriptPath() {
        return SCRIPT_PATH;
    }

    /**
     * Get the SELinux rules script content.
     *
     * @return The SELinux rules script content.
     */
    public static String getScriptContent() {
        return SCRIPT_CONTENT;
    }

    /**
     * Ensure the SELinux rules script exists in {@code post-fs-data.d} and apply it live.
     * <p>
     * The script is only written when missing, then it is executed to apply the rules to the
     * current policy. This method is idempotent and safe to call on every application start.
     *
     * @return {@code true} if the script was installed and applied, {@code false} otherwise.
     */
    public static boolean ensureInstalled() {
        String encoded = Base64.encodeToString(SCRIPT_CONTENT.getBytes(UTF_8), Base64.NO_WRAP);
        Shell.Result result = Shell.cmd(
                "mkdir -p " + POST_FS_DATA_DIR,
                "[ -f " + SCRIPT_PATH + " ] || { echo " + encoded + " | base64 -d > " + SCRIPT_PATH
                        + "; chmod 755 " + SCRIPT_PATH + "; }",
                "sh " + SCRIPT_PATH
        ).exec();
        boolean success = result.isSuccess();
        if (!success) {
            Timber.w("Failed to install SELinux rules script: %s", ShellUtils.mergeAllLines(result.getErr()));
        }
        return success;
    }
}
